  static String tr(BuildContext context, String key) {
    final locale = Localizations.localeOf(context).languageCode;
    final map = _translations[locale] ?? _translations['en'];
    return map?[key] ?? _translations['en']?[key] ?? key;
  }

  static String formatFarmSize(BuildContext context, double hectares) {
    if (hectares < 1.0) {
      final donum = (hectares * 10).round();
      return '$donum ${tr(context, 'unit_donum')}';
    } else {
      return '${hectares.toStringAsFixed(1)} ${tr(context, 'unit_hectare')}';
    }
  }

  /// Map backend irrigation level to a localized display string.
  static String formatIrrigation(BuildContext context, String level) {
    switch (level.toLowerCase()) {
      case 'low':
        return tr(context, 'irrigation_low');
      case 'medium':
        return tr(context, 'irrigation_medium');
      case 'high':
        return tr(context, 'irrigation_high');
      case 'none':
        return tr(context, 'irrigation_none');
      default:
        return level;
    }
  }
  
  /// Countries that use Fahrenheit: US, Liberia, Myanmar
  static bool _usesFahrenheit(BuildContext context) {
    final locale = Localizations.localeOf(context);
    return locale.countryCode == 'US';
  }

  /// Format temperature with locale-appropriate unit (°C or °F)
  static String formatTemperature(BuildContext context, double celsius) {
    if (_usesFahrenheit(context)) {
      final fahrenheit = (celsius * 9 / 5) + 32;
      return '${fahrenheit.toStringAsFixed(1)}°F';
    }
    return '${celsius.toStringAsFixed(1)}°C';
  }

  /// Format rainfall with locale-appropriate unit (mm or inches)
  static String formatRainfall(BuildContext context, double mm) {
    if (_usesFahrenheit(context)) {
      final inches = mm / 25.4;
      return '${inches.toStringAsFixed(1)} in';
    }
    return '${mm.toStringAsFixed(1)} mm';
  }

