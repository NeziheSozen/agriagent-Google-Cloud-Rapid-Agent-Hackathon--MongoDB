  /// Translate a crop name from English to the current locale.
  static String trCrop(BuildContext context, String crop) {
    final locale = Localizations.localeOf(context).languageCode;
    final localeMap = _cropNames[locale];
    final translated = localeMap?[crop.toLowerCase()];
    if (translated != null) return translated;
    return CropTranslator.translate(crop, locale: locale);
  }

